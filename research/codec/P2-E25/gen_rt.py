#!/usr/bin/env python3
"""Generate rt.inc: copies of production kg_serialize / kg_encode_table from the pinned repaired core blob, renamed
rt_serialize / rt_encode_table, with ONE change: a per-leaf codec policy hook (rt_leaf) replaces the single codec/level
and an rt_rans flag gates the rANS trial. Wire output stays the existing KG syntax; the production decoder reads it."""
import hashlib, pathlib, sys
CORE = 'e06467c8872d494b97270811bedf6fd0bac2aa31'
root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[3])
c = (root / 'src/kolmo.c').read_bytes()
if hashlib.sha1(b'blob ' + str(len(c)).encode() + b'\0' + c).hexdigest() != CORE: raise SystemExit('pinned core mismatch')
k = (root / 'src/kgraph.inc').read_text()
i = k.index('static size_t kg_serialize('); j = k.index('\n}\n', i) + 3
ser = k[i:j]
def rep(s, a, b, n=1):
    if s.count(a) != n: raise SystemExit('anchor %r found %d' % (a, s.count(a)))
    return s.replace(a, b)
ser = rep(ser, 'static size_t kg_serialize(', 'static size_t rt_serialize(')
ser = rep(ser, 'int cc = codec == C_CM || codec == C_STORE ? C_LZMA : codec;', 'int lvl = level, cc = rt_leaf(codec, level, s->n, &lvl);')
ser = rep(ser, 'codec_compress(x, cc, level, s->p, s->n, o.p + o.n + 20, zc)', 'codec_compress(x, cc, lvl, s->p, s->n, o.p + o.n + 20, zc)')
ser = rep(ser, 'size_t rz = hb && slow ?', 'size_t rz = hb && slow && rt_rans ?')
e0 = k.index('static size_t kg_encode_table('); e1 = k.index('\n}\n', e0) + 3
enc = k[e0:e1]
enc = rep(enc, 'static size_t kg_encode_table(', 'static size_t rt_encode_table(')
enc = rep(enc, 'kg_serialize(', 'rt_serialize(')
pathlib.Path(__file__).with_name('rt.inc').write_text('/* GENERATED by gen_rt.py from the pinned core; research only. */\n' + ser + enc)
print('ok', len(ser), len(enc))
