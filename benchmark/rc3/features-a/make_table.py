#!/usr/bin/env python3
"""Turn a `kolmo calibrate` table into src/plan/target_table.inc (the built-in table of --target).
Usage: python3 make_table.py calibration.txt > src/plan/target_table.inc"""
import sys
SET = ["speed", "balanced-n", "balanced", "eco", "hc", "ratio-l1", "ratio", "x-l1", "x"]
CLS = ["text", "table", "log", "json", "numeric", "binary"]
t = {}
head = []
for line in open(sys.argv[1]):
    if line.startswith("#"): head.append(line.strip("# \n")); continue
    f = line.split()
    if len(f) >= 4 and f[0] in SET: t[(f[0], f[1])] = [float(x) for x in f[2:]] + [0.0] * (6 - len(f))
print("/* Built-in speed table for --target: per setting, per class (text, table, log, json, numeric, binary),")
print(" * {encode MB/s, decode MB/s, encode setup ms, decode setup ms}. Generated by")
print(" * benchmark/rc3/features-a/make_table.py from `kolmo calibrate` (%s). */" % "; ".join(head))
for s in SET:
    print("    /* %-10s */ {%s}," % (s, ", ".join("{%s}" % ", ".join("%g" % v for v in t[(s, c)]) for c in CLS)))
