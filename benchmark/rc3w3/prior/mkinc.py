"""Writes src/codecs/cm_kprior.inc from the blobs of `cmprior blob` (one per kind of text, model-3 layout):
   python3 -I mkinc.py OUT.inc DIR   reads DIR/k_<kind>.bin for the kinds of src/algo/texttype.c, in order.
Each blob is stored as a raw LZMA2 stream (dictionary 1 MiB, lc 3, lp 0, pb 2), decoded once on first use."""
import lzma, sys, os
KINDS = ['markup', 'json', 'csv', 'log', 'c', 'py', 'js', 'text']   # kinds 1-8 of texttype.c; SQL dumps (9) use the shared prior
out, d = sys.argv[1], sys.argv[2]
F = dict(format=lzma.FORMAT_RAW, filters=[{'id': lzma.FILTER_LZMA2, 'preset': 9 | lzma.PRESET_EXTREME, 'dict_size': 1 << 20, 'lc': 3, 'lp': 0, 'pb': 2}])
o = ['/* Per-kind priors of the context-mixing coder (codec 7, prior id 2 + kind - 1 for kinds 1-8; docs/PRIORS.md). Generated by',
     ' * benchmark/rc3w3/prior/mkinc.py from `cmprior blob` of a model-3 coder trained on public data of each kind (sources:',
     ' * benchmark/rc3w3/prior/RESULTS.md); none of the lane\'s test files was used. Each blob is a raw LZMA2 stream of',
     ' * CM_KP_RAW bytes laid out as cm_kprior_unpack reads it. Fixed data of the format: a changed blob changes the decoded',
     ' * output of streams that use it, so a new prior needs a new id. */']
raw = None; sizes = []
for k in KINDS:
    b = open(os.path.join(d, f'k_{k}.bin'), 'rb').read()
    raw = raw or len(b); assert len(b) == raw
    z = lzma.compress(b, **F); sizes.append(len(z))
    assert lzma.decompress(z, format=lzma.FORMAT_RAW, filters=F['filters']) == b
    o.append(f'static const uint8_t cm_kp_{k}[{len(z)}] = {{')
    for i in range(0, len(z), 32): o.append('  ' + ','.join(str(x) for x in z[i:i + 32]) + ',')
    o.append('};')
o.append(f'#define CM_KP_RAW {raw}')
o.append('static const struct { const uint8_t *z; uint32_t zn; } cm_kp_blob[' + str(len(KINDS)) + '] = {' + ', '.join(f'{{cm_kp_{k}, {s}}}' for k, s in zip(KINDS, sizes)) + '};')
open(out, 'w').write('\n'.join(o) + '\n')
print(' '.join(f'{k}={s}' for k, s in zip(KINDS, sizes)), 'total', sum(sizes))
