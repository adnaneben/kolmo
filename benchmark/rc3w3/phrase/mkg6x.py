# Generates g6x.c, a study copy of src/codecs/gr6.c with a bit-cost census per decision kind (rc3w3 phrase lane).
import re
s = open('src/codecs/gr6.c').read()
s = re.sub(r'\bg6_', 'g6x_', s); s = re.sub(r'\bgr6_', 'gr6x_', s); s = re.sub(r'\bG6_', 'G6X_', s); s = re.sub(r'\bG6K_', 'G6XK_', s)
s = s.replace('codec_gr6', 'codec_gr6x')
s = '/* GENERATED by mkg6x.py from src/codecs/gr6.c (study copy with a bit census). Do not edit. */\n#include <math.h>\ndouble g6x_bits[16]; long g6x_units[16];\n' + s
old = '    int p = (pm + 3 * pa) >> 2; if (p < 1) p = 1; if (p > 4095) p = 4095;\n'
assert old in s
s = s.replace(old, old + '    if (io->enc) { g6x_bits[x->kind] -= log2((bit ? p : 4096 - p) / 4096.0); if (node == 1) g6x_units[x->kind]++; }\n')
s = s.replace('size_t gr6x_compress_pub', 'static size_t gr6x_compress_pub_unused').replace('int gr6x_decompress_pub', 'static int gr6x_decompress_pub_unused')
open('benchmark/rc3w3/phrase/g6x.c', 'w').write(s)
# ---- G6X_ROW: one decision per row: "every field of this row takes the op of the field above" (multi-item flag)
s = open('benchmark/rc3w3/phrase/g6x.c').read()
def rep(old, new):
    global s
    assert old in s, old
    s = s.replace(old, new, 1)
rep('enum { G6XK_NF, G6XK_OP, G6XK_RANK, G6XK_RANK2, G6XK_CDICT, G6XK_GID, G6XK_NUM, G6XK_NUMNEW, G6XK_CHAR, G6XK_PFX, G6X_NKIND };',
    'enum { G6XK_NF, G6XK_OP, G6XK_RANK, G6XK_RANK2, G6XK_CDICT, G6XK_GID, G6XK_NUM, G6XK_NUMNEW, G6XK_CHAR, G6XK_PFX, G6XK_ROW, G6X_NKIND };\n'
    'int g6x_rowmode = 0; static int g6x_force_op = -1; long g6x_rows_flagged, g6x_rows_total, g6x_mismatch; static uint32_t g6x_rowhist;')
# the op decision: forced when the row flag says so
rep('''    g6x_set(M, &x, G6XK_OP, f);
    uint64_t ov = g6x_val(io, &x, (uint64_t)op);''',
'''    uint64_t ov;
    if (g6x_force_op >= 0) { if (io->enc && op != M->aop[f]) g6x_mismatch++; ov = M->aop[f]; }
    else { g6x_set(M, &x, G6XK_OP, f); ov = g6x_val(io, &x, (uint64_t)op); }''')
# dry run of the row's ops (encoder): the op rules of g6x_field, read-only, with the row's values pre-parsed
rep('static void g6x_line_end(g6x_model *M, size_t nf) {', r'''
static int g6x_dry_op(g6x_model *M, int f, const uint8_t *s, size_t n, uint32_t pid) {
    g6x_heap *H = M->H; g6x_col *C = &M->col[f < G6X_MAXC ? f : G6X_MAXC - 1];
    uint32_t id = g6x_intern_get(H, &M->tok, s, n, 0); int64_t v = 0; g6x_fmt fm = {0, 0}; int isnum = g6x_parse(s, n, &v, &fm);
    int64_t pr[4] = {0, 0, 0, 0}; int avail = 0, sel = -1, pos = -1;
    uint32_t pkey = f ? pid : 0xFFFFFFFEu;
    if (f < (int)M->pnf && id != UINT32_MAX && M->aid[f] == id) return G6X_DITTO;
    if (n == 0) return G6X_EMPTY;
    if (isnum && C->has && fm.d == C->fmt.d && fm.w == C->fmt.w && (avail = g6x_predict(M, C, pr)) && (sel = g6x_choose(C, avail)) >= 0 &&
        (v == pr[sel] || id == UINT32_MAX || (pos = g6x_find(&C->list, id)) < 0 || pos >= 2)) return G6X_NUM;
    if (id != UINT32_MAX && g6x_find(&C->list, id) >= 0) return G6X_RANK;
    if (id != UINT32_MAX) {
        if (pkey != UINT32_MAX) { g6x_mtf *pl = g6x_plist(M, pkey, 0); if (pl && g6x_find(pl, id) >= 0) return G6X_RANK2; }
        if (g6x_map_slot(H, &M->cdmap, (uint64_t)(f < G6X_MAXC ? f : G6X_MAXC - 1) << 32 | id, 0)) return G6X_CDICT;
        return G6X_GID;
    }
    return isnum ? G6X_NUMNEW : G6X_NEW;
}
static void g6x_line_end(g6x_model *M, size_t nf) {''')
# encoder row loop: flag before the fields when the field count matches the row above
rep('''            size_t fs = i; int f = 0;
            for (size_t k = i; k <= e; k++) if (k == e || d[k] == sep) { g6x_field(M, io, f++, d + fs, k - fs, NULL, NULL, 0); fs = k + 1; }''',
'''            g6x_force_op = -1;
            if (g6x_rowmode && nf == M->pnf && nf > 1) {
                /* pre-parse the row (formulas read the earlier fields of the same row), then the ops */
                size_t fs2 = i; int f2 = 0; int same = 1; uint32_t pid = 0;
                for (size_t k = i; k <= e; k++) if (k == e || d[k] == sep) {
                    int64_t v = 0; g6x_fmt fm = {0, 0}; int ok = g6x_parse(d + fs2, k - fs2, &v, &fm);
                    M->cv[f2] = v; M->cf[f2] = fm; M->cok[f2] = (uint8_t)ok;
                    if (same) { int op = g6x_dry_op(M, f2, d + fs2, k - fs2, pid); if (op != M->aop[f2]) same = 0; }
                    pid = g6x_intern_get(M->H, &M->tok, d + fs2, k - fs2, 0);
                    f2++; fs2 = k + 1;
                }
                g6x_ctx xr; g6x_set(M, &xr, G6XK_ROW, 0);
                xr.h[3] = g6x_H(g6x_H(G6XK_ROW << 6, 40), g6x_rowhist & 0xff); xr.h[4] = g6x_H(g6x_H(G6XK_ROW, 41), g6x_rowhist & 0xffff);
                g6x_val(io, &xr, (uint64_t)same); g6x_rowhist = g6x_rowhist << 1 | (uint32_t)same;
                g6x_rows_total++; g6x_rows_flagged += same;
                if (same) g6x_force_op = 1;
            }
            size_t fs = i; int f = 0;
            for (size_t k = i; k <= e; k++) if (k == e || d[k] == sep) { g6x_field(M, io, f++, d + fs, k - fs, NULL, NULL, 0); fs = k + 1; }
            g6x_force_op = -1;''')
open('benchmark/rc3w3/phrase/g6x.c', 'w').write(s)
