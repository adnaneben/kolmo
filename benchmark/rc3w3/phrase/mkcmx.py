# Generates cmx.c, a study copy of src/codecs/cm.c (codec 7) with two dictionary-phrase contexts added to model 3.
# Run: python3 benchmark/rc3w3/phrase/mkcmx.py  (from the repository root). The copy is never part of the library.
import re, sys
src = open('src/codecs/cm.c').read()
s = re.sub(r'\bcm_', 'cmx_', src)
s = re.sub(r'\bCM_', 'CMX_', s)
s = re.sub(r'\bbh_', 'bhx_', s)
s = re.sub(r'\bBH_', 'BHX_', s)
s = s.replace('SM_LIM', 'SMX_LIM').replace('kolmo_set_x_tables', 'kolmox_set_x_tables')
s = s.replace('#include "../arch/kernels.h"', '')
s = s.replace('#ifdef KOLMO_CODEC_REGISTRY', '#if 0')
def sub(old, new, count=1):
    global s
    assert s.count(old) >= 1, old
    s = s.replace(old, new, count)
# two more models (30, 31) in model 3
sub('#define CMX_NM3 30', '#define CMX_NM3 32')
# table sizes: the five structure contexts (25..29) stay a quarter; the phrase contexts get half (as models 16-24)
sub('int b = i >= CMX_NM && bb > 18 ? bb - CMX_SMALL - (i >= CMX_NM3 - 5) : bb;',
    'int b = i >= CMX_NM && bb > 18 ? bb - CMX_SMALL - (i >= 25 && i < 30) : bb;')
# same table sizing rule as codec 7 (bits from the original cm_bits_for)
sub('static int cmx_bits_for(size_t n) {', 'static int cmx_bits_for(size_t n) { return cm_bits_for(n); }\nstatic int cmx_bits_for_unused(size_t n) {')
# state: token history
sub('    int mrec;', '    int mrec;\n    uint32_t px_tok, px_hist[8], px_node, px_phr; int px_nh; int px_pend;')
# (A) code bytes as word tokens: single codes are one token, a prefix and the byte after it are one token
sub('        if (((c | 32) >= \'a\' && (c | 32) <= \'z\') || c >= 128) m->word = (m->word + (c | 32) + 1) * 0x3D4D51CBu;',
    '        if (px_codes && (m->px_pend || px_cls[c])) {\n'
    '            if (m->px_pend || px_cls[c] == 1) { uint32_t wc = (m->px_pend ? (m->px_pend << 8 | c) : c) * 0x9E3779B1u + 0x7F4A7C15u; if (m->word) { m->word2 = m->word1; m->word1 = m->word; } m->word2 = m->word1; m->word1 = wc; m->word = 0; m->px_pend = 0; }\n'
    '            else m->px_pend = 256 | c;\n'
    '        } else\n'
    '        if (((c | 32) >= \'a\' && (c | 32) <= \'z\') || c >= 128) m->word = (m->word + (c | 32) + 1) * 0x3D4D51CBu;')
# the contexts, after the structure contexts of model 3
sub('            (void)kq;\n', '            (void)kq;\n            px_update(&m->px_tok, m->px_hist, &m->px_nh, &m->px_node, &m->px_phr, c);\n'
    '            m->h[30] = cmx_hmix(m->px_node * 0x9E3779B1u + m->px_tok * 0x85EBCA6Bu + 30);\n'
    '            m->h[31] = cmx_hmix((px_var ? m->px_node : m->px_phr) * 0xC2B2AE35u + (c4 & (px_var == 2 ? 0xff : 0xffff)) * 0x2545F491u + 31);\n')
hdr = r'''/* GENERATED by mkcmx.py from src/codecs/cm.c: study copy with phrase contexts (rc3w3 phrase lane). Do not edit. */
/* token history -> dictionary phrase contexts. Tokens: a run of letters (and bytes >= 128), or one other byte.
 * px_set holds hashes of every dictionary phrase and of each of its proper prefixes (as token sequences).
 * node: hash of the longest suffix of the token history that is a phrase prefix (what may follow is in the dictionary);
 * phr: hash of the longest suffix that is a whole phrase. */
static uint64_t *px_set; static size_t px_mask; static int px_codes; static uint8_t px_cls[256]; static int px_mode; static uint16_t *px_cnt; static int px_T = 2; static int px_var;
#define PX_CB 22
static inline int px_has(uint32_t h) {
    if (!px_set) return 0;
    uint64_t k = (uint64_t)h | 1ull << 63; size_t q = (size_t)((h * 0x9E3779B97F4A7C15ull) >> 20) & px_mask;
    while (px_set[q]) { if ((px_set[q] & ~(1ull << 62)) == k) return (px_set[q] >> 62 & 1) ? 2 : 1; q = (q + 1) & px_mask; }
    return 0;
}
static inline uint32_t px_th(uint32_t h, uint32_t t) { h = (h + t + 0x51ED27u) * 0x2F0B3A55u; return h ^ (h >> 15); }
static inline int px_wch(uint32_t c) { return ((c | 32) >= 'a' && (c | 32) <= 'z') || c >= 128; }
static inline void px_push(uint32_t *hist, int *nh, uint32_t t) { memmove(hist + 1, hist, 7 * 4); hist[0] = t; if (*nh < 8) (*nh)++; }
static void px_find(uint32_t *hist, int nh, uint32_t *node, uint32_t *phr) {
    uint32_t h = 0, bn = 0, bp = 0;
    if (px_mode == 1) {        /* adaptive: the longest token suffix seen at least px_T times before, then count it */
        if (!px_cnt) px_cnt = calloc((size_t)1 << PX_CB, 2);
        int best = 0;
        for (int k = 0; k < nh; k++) {
            h = px_th(h, hist[k]); uint32_t i = (h * 0x9E3779B1u) >> (32 - PX_CB);
            if (px_cnt[i] >= px_T) { bn = h; best = k + 1; if (k >= 1) bp = h; }
            if (px_cnt[i] < 65535) px_cnt[i]++;
        }
        *node = bn ^ (uint32_t)best; *phr = bp; return;
    }
    for (int k = 0; k < nh; k++) { h = px_th(h, hist[k]); int r = px_has(h); if (r) { bn = h; if (r == 2) bp = h; } }
    *node = bn; *phr = bp;
}
static inline void px_update(uint32_t *tok, uint32_t *hist, int *nh, uint32_t *node, uint32_t *phr, uint32_t c) {
    if (px_wch(c)) { *tok = (*tok + c + 1) * 0x3D4D51CBu; return; }
    if (*tok) { px_push(hist, nh, *tok); *tok = 0; }
    px_push(hist, nh, c + 1); px_find(hist, *nh, node, phr);
}
'''
s = s.replace('#include <math.h>', hdr + '#include <math.h>', 1)
# the word-run token ends at a non-letter: phrases are found at token ends only; a letter extends the current token, and
# the node / phrase of the history before it stay the context (combined with the partial token in h[30])
s = s.replace('->cmx_hash', '->cm_hash').replace('->cmx_dot', '->cm_dot').replace('->cmx_train', '->cm_train')
import os
if os.environ.get('UTF8FIX'):
    # study only: no phrase models (30 as codec 7), and the word hash folds case on ASCII letters only
    s = s.replace('#define CMX_NM3 32', '#define CMX_NM3 30')
    s = s.replace('            px_update(&m->px_tok', '            if (0) px_update(&m->px_tok')
    s = s.replace("            m->h[30] = cmx_hmix", "            if (0) m->h[30] = cmx_hmix").replace("            m->h[31] = cmx_hmix", "            if (0) m->h[31] = cmx_hmix")
    s = s.replace("|| c >= 128) m->word = (m->word + (c | 32) + 1) * 0x3D4D51CBu;", "|| c >= 128) m->word = (m->word + (c < 128 ? c | 32 : c) + 1) * 0x3D4D51CBu;")
open('benchmark/rc3w3/phrase/cmx.c', 'w').write(s)
print('ok')
