import json,sys,math,collections,os
R=sys.argv[1]; out=[]
P=lambda *a: out.append(" ".join(str(x) for x in a))
def gm(xs): xs=[x for x in xs if x and x>0]; return math.exp(sum(map(math.log,xs))/len(xs)) if xs else float('nan')
for s in sys.argv[2:]:
    r=json.load(open(f"{R}/{s}/report.json"))
    P(f"\n## {s}  statuses {r['status_counts']}  missing {len(r['missing_pairs'])}")
    st=collections.defaultdict(dict)
    for x in r['stats']: st[x['codec']][x['input']]=x
    P("\n| codec | files | total comp B | ratio(total) | enc MiB/s (total) | dec MiB/s (total) | gm enc RSS avg MiB | gm dec RSS avg MiB | max enc peak MiB | max dec peak MiB | max thr e/d | nondet |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c,d in sorted(st.items()):
        o=sum(x['input_bytes'] for x in d.values()); cb=sum(x['comp_bytes'] for x in d.values())
        e=sum(x['enc_wall']['median'] for x in d.values()); dd=sum(x['dec_wall']['median'] for x in d.values())
        P(f"| {c} | {len(d)} | {cb:,} | {o/cb:.3f} | {o/e/2**20:.1f} | {o/dd/2**20:.1f} | {gm([x['enc_rss_avg']['median'] for x in d.values()])/2**20:.1f} | {gm([x['dec_rss_avg']['median'] for x in d.values()])/2**20:.1f} | {max(x['enc_peak_kernel_max'] for x in d.values())/2**20:.0f} | {max(x['dec_peak_kernel_max'] for x in d.values())/2**20:.0f} | {max(x['enc_threads_max'] for x in d.values())}/{max(x['dec_threads_max'] for x in d.values())} | {sum(not x['deterministic_size'] for x in d.values())} |")
    pairs=collections.defaultdict(list)
    for x in r['comparisons']: pairs[(x['candidate'],x['reference'])].append(x)
    if pairs:
        P("\n| candidate vs reference | files | total size change | size W/T/L | gm enc speedup | enc W/T/L | gm dec speedup | dec W/T/L | enc RSSavg W/T/L | dec RSSavg W/T/L | dec peak W/T/L |")
        P("|---|---|---|---|---|---|---|---|---|---|---|")
    for (c,ref),xs in pairs.items():
        cb=sum(st[c][x['input']]['comp_bytes'] for x in xs); rb=sum(st[ref][x['input']]['comp_bytes'] for x in xs)
        wtl=lambda k: "/".join(str(sum(1 for x in xs if x[k]==v)) for v in ("win","tie","loss"))
        P(f"| {c} vs {ref} | {len(xs)} | {100*(rb-cb)/rb:+.2f}% smaller | {wtl('size')} | {gm([x['encode_speedup_median'] for x in xs]):.3f}x | {wtl('encode')} | {gm([x['decode_speedup_median'] for x in xs]):.3f}x | {wtl('decode')} | {wtl('encode_mem_avg')} | {wtl('decode_mem_avg')} | {wtl('decode_mem_peak')} |")
open(f"{R}/SUMMARY.md","w").write("# Holdout summary (generated by tools/summarize_reports.py from report.json files)\n"+"\n".join(out)+"\n")
print("\n".join(out))
