#!/usr/bin/env python3
"""Tables from raw/rows.jsonl (benchmark/impact/run.py).
usage: summarize.py [FEATURE...] > tables.md

For each feature row the reference is the `base` row of the same file, level and thread count (frames do not depend
on the thread count; the script checks it). Columns:
  kept   frame size with the feature as a candidate (kept per block only when smaller), vs the level's frame
  forced the trial's payload on every block it coded, vs the level's payload (blocks.forced_sum / blocks.base_sum)
  c x / d x   compress / decompress wall time vs the level's (same thread count; machine load in the rows)
  rss x  peak compress RSS vs the level's
"""
import json, os, sys, collections, statistics
HERE = os.path.dirname(os.path.abspath(__file__))
rows = [json.loads(l) for l in open(os.path.join(HERE, "raw", "rows.jsonl")) if l.strip()]
base = {}
for r in rows:
    if r["feature"] == "base" and r.get("ok"): base[(r["file"], r["level"], r["threads"])] = r
tbase = dict(base); tbase.update({(r["file"], r["level"], r["threads"]): r for r in rows if r["feature"] == "base2" and r.get("ok")})   # timing reference (low load)
LV = lambda l: "U" if l == 10 else str(l)

def pct(a, b): return 100.0 * (a / b - 1.0) if b else float("nan")

def check_threads():
    by = collections.defaultdict(set)
    for r in rows:
        if r.get("ok"): by[(r["feature"], r["file"], r["level"])].add(r.get("frame_sha256"))
    bad = [k for k, v in by.items() if len(v) > 1]
    return bad

def feature_rows(feat):
    out = []
    for r in rows:
        if r["feature"] != feat or not r.get("ok"): continue
        b = base.get((r["file"], r["level"], r["threads"])); t = tbase.get((r["file"], r["level"], r["threads"]))
        blk = r.get("blocks") or {}
        fz = pct(blk["forced_sum"], blk["base_sum"]) if blk.get("base_sum") and blk.get("tried") else None
        out.append(dict(r, kept_pct=pct(r["size"], b["size"]) if b else None, forced_pct=fz,
                        cx=r["c_wall"] / t["c_wall"] if t and t["c_wall"] else None,
                        dx=r["d_wall"] / t["d_wall"] if t and t["d_wall"] else None,
                        ccx=r["c_cpu"] / t["c_cpu"] if t and t["c_cpu"] else None,
                        rssx=r["c_rss"] / t["c_rss"] if t and t["c_rss"] else None,
                        drssx=r["d_rss"] / t["d_rss"] if t and t["d_rss"] else None, base=t))
    return out

def fmt(x, d=1, plus=True):
    if x is None: return "·"
    return ("%+.*f" if plus else "%.*f") % (d, x)

def table(feat, threads=1):
    R = [r for r in feature_rows(feat) if r["threads"] == threads]
    if not R: return ""
    levels = sorted({r["level"] for r in R}); files = sorted({(r["set"], r["kind"], r["file"]) for r in R}, key=lambda t: (t[1], t[0], t[2]))
    idx = {(r["file"], r["level"]): r for r in R}
    o = ["", "#### %s, size vs the level's choice: kept %% / forced %% (T%d)" % (feat, threads), "",
         "| set | kind | file | " + " | ".join("L" + LV(l) for l in levels) + " |", "|---|---|---|" + "---:|" * len(levels)]
    for s, k, f in files:
        cells = []
        for l in levels:
            r = idx.get((f, l))
            if not r: cells.append(""); continue
            a = fmt(r["kept_pct"]); b = fmt(r["forced_pct"]) if r["forced_pct"] is not None and abs(r["forced_pct"] - (r["kept_pct"] or 0)) > 0.05 else ""
            cells.append(a + (" / " + b if b else ""))
        o.append("| %s | %s | %s | %s |" % (s, k, os.path.basename(f).split("__", 1)[1], " | ".join(cells)))
    return "\n".join(o)

def speed_table(feat):
    R = [r for r in feature_rows(feat) if r["kept_pct"] is not None and r["kept_pct"] < -0.05]
    if not R: return ""
    o = ["", "#### %s where it wins: speed and memory against the level's choice" % feat, "",
         "| file | L | T | size % | comp MB/s (level) | dec MB/s (level) | comp CPU x | peak RSS comp / dec x | load |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in sorted(R, key=lambda r: (r["file"], r["level"], r["threads"])):
        b = r["base"]
        o.append("| %s | %s | %d | %s | %.1f (%.1f) | %.1f (%.1f) | %s | %s / %s | %.0f |" % (os.path.basename(r["file"]).split("__", 1)[1], LV(r["level"]), r["threads"], fmt(r["kept_pct"], 2),
                 r["c_mbs"], b["c_mbs"], r["d_mbs"], b["d_mbs"], fmt(r["ccx"], 2, False), fmt(r["rssx"], 2, False), fmt(r["drssx"], 2, False), r["load1"]))
    return "\n".join(o)

if __name__ == "__main__":
    feats = sys.argv[1:] or sorted({r["feature"] for r in rows} - {"base", "base2"})
    bad = check_threads()
    print("<!-- generated by summarize.py from %d rows; frames that differ between thread counts: %d -->" % (len(rows), len(bad)))
    fails = [r for r in rows if not r.get("ok")]
    if fails: print("\nFAILED cells: " + "; ".join("%s %s L%s T%s: %s" % (r["feature"], r["file"], r["level"], r["threads"], r.get("error", "")[:120]) for r in fails))
    for f in feats:
        print("\n### " + f)
        print(table(f, 1))
        print(speed_table(f))
