#!/usr/bin/env python3
"""Generate the paper's figures and tables from the raw measurements in docs/paper/data/.

usage: python3 docs/paper/figures/make_figures.py

Standard library only. Writes LaTeX fragments into docs/paper/generated/:
  fig-pareto.tex        pgfplots axes: Silesia ratio vs compress and vs decompress speed (lzbench, one thread)
  tab-silesia.tex       Kolmo levels on Silesia next to the nearest general-purpose rival
  tab-corpora.tex       enwik8 and Canterbury at selected levels
  tab-silesia-files.tex Silesia per file, Kolmo -3 against zstd -3 / zstd -19 / xz -9
  tab-structured.tex    the 20-file structured panel against OpenZL 0.3.0 (untrained profiles)
  tab-mt.tex            command-line runs on Silesia, one thread and all cores, with memory
  numbers.tex           \\newcommand macros for every number quoted in the running text

Every fragment starts with a comment naming the data file it came from, so each number in the PDF traces to
docs/paper/data/<file> (copied unchanged, except that lzbench's absolute file paths were cut to the base name, from
the measurement workspace evidence/mkt-0.0.2/ of 2026-11-23; see docs/paper/data/README.md).
"""
import csv
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
DATA = os.path.join(PAPER, "data")
OUT = os.path.join(PAPER, "generated")
os.makedirs(OUT, exist_ok=True)


# ---------------------------------------------------------------- loading

def lzbench(*names):
    """Rows of lzbench CSV files: name -> (ratio, comp MiB/s, decomp MiB/s, comp bytes, file)."""
    rows = {}
    for n in names:
        with open(os.path.join(DATA, n)) as f:
            for r in csv.DictReader(f):
                name = r["Compressor name"]
                if name == "memcpy":
                    continue
                orig, comp = int(r["Original size"]), int(r["Compressed size"])
                key = (name, r.get("Filename") or n)
                rows[key] = dict(name=name, ratio=orig / comp, c=float(r["Compression speed"]),
                                 d=float(r["Decompression speed"]), size=comp, orig=orig, src=n)
    return rows


def corpus(stem):
    rows = lzbench(f"lzb-fast-{stem}.csv", f"lzb-slow-{stem}.csv")
    return {k[0]: v for k, v in rows.items()}


def short(name):
    """'zstd 1.5.7 -19' -> 'zstd -19'; 'kolmo 0.0.2 -10' -> 'Kolmo -U'."""
    parts = name.replace("'", "").split()
    tool = parts[0]
    lvl = " ".join(p for p in parts[2:] if not p.startswith("-d")) if len(parts) > 2 else ""
    if tool == "kolmo":
        tool = "Kolmo"
        if lvl == "-10":
            lvl = "-U"
    return f"{tool} {lvl}".strip()


def kolmo_level(name):
    return name.startswith("kolmo ")


def fmt_ratio(x):
    return f"{x:.3f}" if x < 10 else f"{x:.2f}" if x < 100 else f"{x:.1f}"


def fmt_speed(x):
    return f"{x:.1f}" if x < 10 else f"{x:.0f}"


def write(name, text, src):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(f"% generated by docs/paper/figures/make_figures.py from docs/paper/data/{src}; do not edit\n")
        f.write(text)


# ---------------------------------------------------------------- Pareto figure

def pareto(points, speed):
    """Indices of points not dominated in (ratio, speed): no other point has both >= and one >."""
    keep = []
    for i, p in enumerate(points):
        dom = any(q["ratio"] >= p["ratio"] and q[speed] >= p[speed] and (q["ratio"] > p["ratio"] or q[speed] > p[speed])
                  for j, q in enumerate(points) if j != i)
        if not dom:
            keep.append(i)
    return sorted(keep, key=lambda i: points[i][speed])


FAMILIES = [  # (prefix, legend, pgfplots style)
    ("kolmo", "Kolmo 0.0.2", "ppkolmo"),
    ("zstd", "zstd 1.5.7", "ppzstd"),
    ("brotli", "brotli 1.2.0", "ppbrotli"),
    ("xz", "xz 5.8.4", "ppxz"),
    ("lz4", "lz4 / lz4hc", "pplzfour"),
    ("lzav", "lzav 7.1", "pplzav"),
    ("libdeflate", "libdeflate", "ppdeflate"),
    ("bzip3", "bzip3 / bsc / bzip2", "ppbwt"),
    ("bsc", None, "ppbwt"),
    ("bzip2", None, "ppbwt"),
    ("kanzi", "kanzi 2.6.0", "ppkanzi"),
    ("zpaq", "zpaq / ppmd8", "ppcm"),
    ("ppmd8", None, "ppcm"),
]


def family(name):
    for pre, legend, style in FAMILIES:
        if name.split()[0] == pre:
            return pre, legend, style
    return None


def fig_pareto():
    rows = list(corpus("silesia.tar").values())
    pts = [r for r in rows if family(r["name"])]  # drops snappy, zxc, openzl 'generic' (= zstd -6 bytes)
    out = []
    for axis, speed, xlabel in (("c", "c", "Compression speed (MiB/s, one thread, log scale)"),
                                ("d", "d", "Decompression speed (MiB/s, one thread, log scale)")):
        out.append(r"\begin{tikzpicture}")
        out.append(r"\begin{semilogxaxis}[paretoaxis, xlabel={%s}, ylabel={Ratio (Silesia)}%s]" %
                   (xlabel, ", legend to name=paretolegend" if axis == "c" else ""))
        front = pareto(pts, speed)
        out.append(r"\addplot[frontier] coordinates {%s};" %
                   " ".join(f"({pts[i][speed]:.3f},{pts[i]['ratio']:.4f})" for i in front))
        if axis == "c":
            out.append(r"\addlegendentry{Pareto front}")
        seen = set()
        for pre, legend, style in FAMILIES:
            fam = [p for p in pts if p["name"].split()[0] == pre]
            if pre == "kolmo":  # join Kolmo's points in level order, the path a user moves along
                fam.sort(key=lambda p: int(p["name"].split()[-1].lstrip("-")))
            else:
                fam.sort(key=lambda p: p[speed])
            if not fam:
                continue
            line = pre in ("kolmo", "zstd", "brotli", "xz", "ppkanzi")
            coords = " ".join(f"({p[speed]:.3f},{p['ratio']:.4f})" for p in fam)
            opt = style + ("" if line else ", only marks")
            if legend is None or style in seen:
                opt += ", forget plot"
            out.append(r"\addplot[%s] coordinates {%s};" % (opt, coords))
            if legend and style not in seen and axis == "c":
                out.append(r"\addlegendentry{%s}" % legend)
            seen.add(style)
        for p in pts:  # label Kolmo levels
            if kolmo_level(p["name"]):
                lvl = short(p["name"]).split()[1]
                out.append(r"\node[kolmolabel] at (axis cs:%.3f,%.4f) {%s};" % (p[speed], p["ratio"], lvl))
        out.append(r"\end{semilogxaxis}")
        out.append(r"\end{tikzpicture}")
        out.append("%")
    write("fig-pareto.tex", "\n".join(out) + "\n", "lzb-fast-silesia.tar.csv, lzb-slow-silesia.tar.csv")


# ---------------------------------------------------------------- tables

RIVALS = {  # Kolmo level -> rivals shown next to it (from the lzbench lineup, nearest in ratio or role)
    "-1": ["lzav 7.1 -1", "lz4 1.11.0"],
    "-2": ["zstd 1.5.7 -1"],
    "-3": ["zstd 1.5.7 -3", "zstd 1.5.7 -12"],
    "-4": ["zstd 1.5.7 -19"],
    "-5": ["brotli 1.2.0 -11"],
    "-6": ["xz 5.8.4 -9"],
    "-7": ["bzip3 1.5.4 -5"],
    "-8": ["bsc 3.3.12 -m0 -e2", "zpaq 7.15 -4"],
    "-9": ["zpaq 7.15 -5", "kanzi 2.6.0 -9"],
    "-10": [],
}


def tab_silesia(nums):
    s = corpus("silesia.tar")
    lines = [r"\begin{tabular}{@{}lrrr@{\quad}lrrr@{}}", r"\toprule",
             r"\multicolumn{4}{c}{Kolmo 0.0.2} & \multicolumn{4}{c}{Rival} \\",
             r"\cmidrule(r){1-4}\cmidrule(l){5-8}",
             r"Level & Ratio & C & D & Codec & Ratio & C & D \\", r"\midrule"]
    for lvl, rivals in RIVALS.items():
        k = s[f"kolmo 0.0.2 {lvl}"]
        nums[f"SilK{lvl[1:]}R"] = fmt_ratio(k["ratio"])
        nums[f"SilK{lvl[1:]}C"] = fmt_speed(k["c"])
        nums[f"SilK{lvl[1:]}D"] = fmt_speed(k["d"])
        kcol = f"{short(k['name']).split()[1]} & {fmt_ratio(k['ratio'])} & {fmt_speed(k['c'])} & {fmt_speed(k['d'])}"
        if not rivals:
            lines.append(kcol + r" & \multicolumn{4}{l}{(highest ratio of the lineup)} \\")
        for i, rv in enumerate(rivals):
            r = s[rv]
            lines.append((kcol if i == 0 else " & & & ") +
                         f" & {short(rv)} & {fmt_ratio(r['ratio'])} & {fmt_speed(r['c'])} & {fmt_speed(r['d'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    for rv in ["zstd 1.5.7 -3", "zstd 1.5.7 -19", "zstd 1.5.7 -12", "xz 5.8.4 -9", "zpaq 7.15 -5", "lzav 7.1 -1",
               "bsc 3.3.12 -m0 -e2", "bzip3 1.5.4 -5", "brotli 1.2.0 -11", "zstd 1.5.7 -1"]:
        key = "Sil" + short(rv).replace(" ", "").replace("-", "").replace(".", "")
        r = s[rv]
        nums[key + "R"], nums[key + "C"], nums[key + "D"] = fmt_ratio(r["ratio"]), fmt_speed(r["c"]), fmt_speed(r["d"])
    k6, xz = s["kolmo 0.0.2 -6"], s["xz 5.8.4 -9"]
    nums["SilSixVsXzDec"] = f"{k6['d'] / xz['d']:.1f}"
    nums["SilSixVsXzEnc"] = f"{k6['c'] / xz['c']:.1f}"
    k3, z3 = s["kolmo 0.0.2 -3"], s["zstd 1.5.7 -3"]
    nums["SilThreeVsZstdPct"] = f"{(1 - k3['size'] / z3['size']) * 100:.0f}"
    nums["SilThreeDecFrac"] = f"{k3['d'] / z3['d']:.2f}"
    k4, z19 = s["kolmo 0.0.2 -4"], s["zstd 1.5.7 -19"]
    nums["SilFourVsZnineteenPct"] = f"{(k4['size'] / z19['size'] - 1) * 100:.1f}"
    nums["SilFourVsZnineteenEnc"] = f"{k4['c'] / z19['c']:.0f}"
    k9, zp = s["kolmo 0.0.2 -9"], s["zpaq 7.15 -5"]
    nums["SilNineVsZpaqDec"] = f"{k9['d'] / zp['d']:.0f}"
    nums["SilNineVsZpaqEnc"] = f"{k9['c'] / zp['c']:.0f}"
    write("tab-silesia.tex", "\n".join(lines) + "\n", "lzb-fast-silesia.tar.csv, lzb-slow-silesia.tar.csv")


def tab_corpora(nums):
    e, c = corpus("enwik8"), corpus("canterbury.tar")
    names = ["kolmo 0.0.2 -1", "kolmo 0.0.2 -3", "kolmo 0.0.2 -6", "kolmo 0.0.2 -7", "kolmo 0.0.2 -8",
             "kolmo 0.0.2 -9", "kolmo 0.0.2 -10", "zstd 1.5.7 -3", "zstd 1.5.7 -19", "xz 5.8.4 -9",
             "brotli 1.2.0 -11", "bsc 3.3.12 -m0 -e2", "bzip3 1.5.4 -10", "kanzi 2.6.0 -9", "zpaq 7.15 -5"]
    lines = [r"\begin{tabular}{@{}lrrr@{\quad}rrr@{}}", r"\toprule",
             r" & \multicolumn{3}{c}{enwik8 (100\,MB)} & \multicolumn{3}{c}{Canterbury (2.8\,MB tar)} \\",
             r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
             r"Codec & Ratio & C & D & Ratio & C & D \\", r"\midrule"]
    for n in names:
        a, b = e[n], c[n]
        cells = []
        for r in (a, b):
            cells += [fmt_ratio(r["ratio"]), fmt_speed(r["c"]), fmt_speed(r["d"])]
        if n == "zstd 1.5.7 -3":
            lines.append(r"\midrule")
        lines.append(f"{short(n)} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    for n, key in (("kolmo 0.0.2 -3", "KThree"), ("kolmo 0.0.2 -2", "KTwo"), ("kolmo 0.0.2 -6", "KSix"),
                   ("kolmo 0.0.2 -7", "KSeven"), ("kolmo 0.0.2 -9", "KNine"), ("kolmo 0.0.2 -10", "KU"),
                   ("zstd 1.5.7 -3", "ZThree"), ("zstd 1.5.7 -1", "ZOne"), ("zpaq 7.15 -5", "Zpaq"),
                   ("bzip3 1.5.4 -5", "Bzipthree"), ("bsc 3.3.12 -m0 -e2", "Bsc"), ("kanzi 2.6.0 -9", "Kanzi")):
        nums["Cant" + key] = fmt_ratio(c[n]["ratio"])
        nums["Enw" + key] = fmt_ratio(e[n]["ratio"])
    nums["EnwKUBytes"] = f"{e['kolmo 0.0.2 -10']['size']:,}".replace(",", "{,}")
    nums["EnwKEightBytes"] = f"{e['kolmo 0.0.2 -8']['size']:,}".replace(",", "{,}")
    nums["EnwKNineBytes"] = f"{e['kolmo 0.0.2 -9']['size']:,}".replace(",", "{,}")
    write("tab-corpora.tex", "\n".join(lines) + "\n",
          "lzb-{fast,slow}-enwik8.csv, lzb-{fast,slow}-canterbury.tar.csv")


SIL_DESC = {"dickens": "English text", "mozilla": "executables (tar)", "mr": "MRI image", "nci": "chemical DB",
            "ooffice": "x86 DLL", "osdb": "database", "reymont": "Polish text", "samba": "source (tar)",
            "sao": "star catalog", "webster": "dictionary", "x-ray": "12-bit X-ray", "xml": "XML (tar)"}


def tab_silesia_files(nums):
    rows = lzbench("lzb-silesia-files.csv")
    by = {}
    for (name, fn), r in rows.items():
        by.setdefault(fn, {})[name] = r
    order = sorted(by, key=lambda f: -by[f]["kolmo 0.0.2 -3"]["ratio"] / by[f]["zstd 1.5.7 -3"]["ratio"])
    cols = ["zstd 1.5.7 -3", "zstd 1.5.7 -19", "xz 5.8.4 -9", "kolmo 0.0.2 -3", "kolmo 0.0.2 -9"]
    lines = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
             r"File & Content & zstd -3 & zstd -19 & xz -9 & Kolmo -3 & Kolmo -9 & $\Delta_3$ \\", r"\midrule"]
    for fn in order:
        b = by[fn]
        gain = (b["kolmo 0.0.2 -3"]["ratio"] / b["zstd 1.5.7 -3"]["ratio"] - 1) * 100
        cells = [fmt_ratio(b[c]["ratio"]) for c in cols]
        lines.append(f"{fn} & {SIL_DESC.get(fn, '')} & " + " & ".join(cells) + f" & {'%+.0f' % gain if round(gain) != 0 else '0'}\\% \\\\")
        nums["File" + fn.replace("-", "") + "Gain"] = f"{gain:.0f}"
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab-silesia-files.tex", "\n".join(lines) + "\n", "lzb-silesia-files.csv")


def tab_structured(nums):
    d = json.load(open(os.path.join(DATA, "openzl.json")))
    lines = [r"\begin{tabular}{@{}llrrrrrrl@{}}", r"\toprule",
             r"File & Type & zstd -3 & xz -9 & OpenZL & Kolmo -3 & Kolmo -5 & Kolmo best & Lvl \\", r"\midrule"]
    score = {"-3": [0, 0, 0], "-5": [0, 0, 0], "best": [0, 0, 0]}
    TIE = 0.01  # within 1% of each other counts as a tie

    def cmp(k, o):
        return 1 if abs(k / o - 1) <= TIE else (0 if k > o else 2)   # index into [win, tie, loss]

    for fn, v in d.items():
        r = {x["tool"]: x for x in v["rows"]}
        oz = max((x for t, x in r.items() if t.startswith("openzl")), key=lambda x: x["ratio"])
        prof = oz["tool"].split("-p ")[1].split()[0].rstrip("]")
        kl = {t.split()[1]: x for t, x in r.items() if t.startswith("kolmo")}
        kb_lvl, kb = max(kl.items(), key=lambda kv: kv[1]["ratio"])
        for key, x in (("-3", kl["-3"]), ("-5", kl["-5"]), ("best", kb)):
            score[key][cmp(x["ratio"], oz["ratio"])] += 1
        vals = [r["zstd -3"]["ratio"], r["xz -9"]["ratio"], oz["ratio"], kl["-3"]["ratio"], kl["-5"]["ratio"],
                kb["ratio"]]
        top = max(vals[2:])
        cells = []
        for i, x in enumerate(vals):
            s = f"{x:.2f}" if x < 100 else f"{x:.1f}"
            if i >= 2 and x == top:
                s = r"\textbf{" + s + "}"
            cells.append(s)
        fname = fn.replace("_", r"\_")
        if len(fname) > 22:
            fname = fname[:20] + r"\ldots"
        lines.append(f"{fname} & {v['area'].replace('_', ' ')} & " + " & ".join(cells) +
                     f" & {kb_lvl} \\\\")
        nums["Panel" + "".join(ch for ch in fn.split(".")[0] if ch.isalpha()) + "Prof"] = prof
    lines += [r"\bottomrule", r"\end{tabular}"]
    for key, (w, t, l) in score.items():
        k = key.strip("-").replace("3", "Three").replace("5", "Five").replace("best", "Best")
        nums[f"Panel{k}Win"], nums[f"Panel{k}Tie"], nums[f"Panel{k}Loss"] = str(w), str(t), str(l)
    nums["PanelFiles"] = str(len(d))
    write("tab-structured.tex", "\n".join(lines) + "\n", "openzl.json")


def tab_mt(nums):
    d = json.load(open(os.path.join(DATA, "mt-result.json")))["results"]
    pairs = [("kolmo -3", "kolmo -3 -T1", "kolmo -3 -T0"), ("zstd -3", "zstd -3 -T1", "zstd -3 -T0"),
             ("kolmo -7", "kolmo -7 -T1", "kolmo -7 -T0"), ("zstd -19", "zstd -19 -T1", "zstd -19 -T0"),
             ("kolmo -9", "kolmo -9 -T1", "kolmo -9 -T0"), ("xz -9", "xz -9 -T1", "xz -9 -T0"),
             ("bzip3", "bzip3 -j1", "bzip3 -j10")]
    lines = [r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r" & & \multicolumn{2}{c}{1 thread $\rightarrow$ 10 threads (MiB/s)} & \multicolumn{2}{c}{Peak RSS, 1 thread (MB)} \\",
             r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
             r"Tool & Ratio & Compress & Decompress & Compress & Decompress \\", r"\midrule"]
    for label, a, b in pairs:
        x, y = d[a], d[b]
        name = label.replace("kolmo", "Kolmo")
        lines.append(f"{name} & {x['ratio']:.3f} & {fmt_speed(x['enc_mibs'])} $\\rightarrow$ {fmt_speed(y['enc_mibs'])}"
                     f" & {fmt_speed(x['dec_mibs'])} $\\rightarrow$ {fmt_speed(y['dec_mibs'])}"
                     f" & {x['enc_rss_mb']:.0f} & {x['dec_rss_mb']:.0f} \\\\")
        k = label.replace(" ", "").replace("-", "").capitalize()
        nums[f"Mt{k}EncRss"] = f"{x['enc_rss_mb']:.0f}"
        nums[f"Mt{k}DecRss"] = f"{x['dec_rss_mb']:.0f}"
        nums[f"Mt{k}DecOne"] = fmt_speed(x["dec_mibs"])
        nums[f"Mt{k}DecAll"] = fmt_speed(y["dec_mibs"])
        nums[f"Mt{k}EncAll"] = fmt_speed(y["enc_mibs"])
    lines += [r"\bottomrule", r"\end{tabular}"]
    nums["MtThreeVsZstdDecAll"] = f"{d['kolmo -3 -T0']['dec_mibs'] / d['zstd -3 -T0']['dec_mibs']:.1f}"
    write("tab-mt.tex", "\n".join(lines) + "\n", "mt-result.json")


def macro_name(k):
    digits = "Zero One Two Three Four Five Six Seven Eight Nine".split()
    out = "".join(digits[int(ch)] if ch.isdigit() else ch for ch in k if ch.isalnum())
    return "num" + out


def main():
    nums = {}
    fig_pareto()
    tab_silesia(nums)
    tab_corpora(nums)
    tab_silesia_files(nums)
    tab_structured(nums)
    tab_mt(nums)
    body = "".join(f"\\newcommand{{\\{macro_name(k)}}}{{{v}}}\n" for k, v in sorted(nums.items()))
    write("numbers.tex", body, "lzb-*.csv, openzl.json, mt-result.json")
    print(f"wrote {len(os.listdir(OUT))} files to {os.path.relpath(OUT)}; {len(nums)} number macros")


if __name__ == "__main__":
    main()
