def tab_silesia_files(nums):
    rows = lzbench("lzb-silesia-files.csv")
    by = {}
    for (name, fn), r in rows.items():
        by.setdefault(fn, {})[name] = r
    order = sorted(by, key=lambda f: -by[f]["kolmo 0.0.2 -3"]["ratio"] / by[f]["zstd 1.5.7 -3"]["ratio"])
    cols = ["zstd 1.5.7 -3", "zstd 1.5.7 -19", "xz 5.8.4 -9", "kolmo 0.0.2 -3", "kolmo 0.0.2 -9"]
    lines = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
             r"File & Content & zstd -3 & zstd -19 & xz -9 & Kolmo -3 & Kolmo -9 & $\Delta_3$ \\", r"\midrule"]
    for fn in order:
        b = by[fn]
        gain = (b["kolmo 0.0.2 -3"]["ratio"] / b["zstd 1.5.7 -3"]["ratio"] - 1) * 100
        cells = [fmt_ratio(b[c]["ratio"]) for c in cols]
        lines.append(f"{fn} & {SIL_DESC.get(fn, '')} & " + " & ".join(cells) + f" & {'%+.0f' % gain if round(gain) != 0 else '0'}\\% \\\\")
        nums["File" + fn.replace("-", "") + "Gain"] = f"{gain:.0f}"
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab-silesia-files.tex", "\n".join(lines) + "\n", "lzb-silesia-files.csv")


def tab_structured(nums):
    d = json.load(open(os.path.join(DATA, "openzl.json")))
    lines = [r"\begin{tabular}{@{}llrrrrrrl@{}}", r"\toprule",
             r"File & Type & zstd -3 & xz -9 & OpenZL & Kolmo -3 & Kolmo -5 & Kolmo best & Lvl \\", r"\midrule"]
    score = {"-3": [0, 0, 0], "-5": [0, 0, 0], "best": [0, 0, 0]}
    TIE = 0.01  # within 1% of each other counts as a tie

    def cmp(k, o):
        return 1 if abs(k / o - 1) <= TIE else (0 if k > o else 2)   # index into [win, tie, loss]

    for fn, v in d.items():
        r = {x["tool"]: x for x in v["rows"]}
        oz = max((x for t, x in r.items() if t.startswith("openzl")), key=lambda x: x["ratio"])
        prof = oz["tool"].split("-p ")[1].split()[0].rstrip("]")
        kl = {t.split()[1]: x for t, x in r.items() if t.startswith("kolmo")}
        kb_lvl, kb = max(kl.items(), key=lambda kv: kv[1]["ratio"])
        for key, x in (("-3", kl["-3"]), ("-5", kl["-5"]), ("best", kb)):
            score[key][cmp(x["ratio"], oz["ratio"])] += 1
        vals = [r["zstd -3"]["ratio"], r["xz -9"]["ratio"], oz["ratio"], kl["-3"]["ratio"], kl["-5"]["ratio"],
                kb["ratio"]]
        top = max(vals[2:])
        cells = []
        for i, x in enumerate(vals):
            s = f"{x:.2f}" if x < 100 else f"{x:.1f}"
            if i >= 2 and x == top:
                s = r"\textbf{" + s + "}"
            cells.append(s)
        fname = fn.replace("_", r"\_")
        if len(fname) > 22:
            fname = fname[:20] + r"\ldots"
        lines.append(f"{fname} & {v['area'].replace('_', ' ')} & " + " & ".join(cells) +
                     f" & {kb_lvl} \\\\")
        nums["Panel" + "".join(ch for ch in fn.split(".")[0] if ch.isalpha()) + "Prof"] = prof
    lines += [r"\bottomrule", r"\end{tabular}"]
    for key, (w, t, l) in score.items():
        k = key.strip("-").replace("3", "Three").replace("5", "Five").replace("best", "Best")
        nums[f"Panel{k}Win"], nums[f"Panel{k}Tie"], nums[f"Panel{k}Loss"] = str(w), str(t), str(l)
    nums["PanelFiles"] = str(len(d))
    write("tab-structured.tex", "\n".join(lines) + "\n", "openzl.json")


